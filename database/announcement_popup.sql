-- AnnouncementPopupJpaEntity 에서 Hibernate 로 생성하는 DDL (PostgreSQLDialect).
-- 컨벤션에 맞춰 IF NOT EXISTS 와 주석만 추가했다.
-- 이 파일은 문서다. 실제 스키마의 근거는 JPA 애노테이션이고, 그래서 엔티티에 없는 제약(FK 등)은 일부러 넣지 않았다.
-- (다른 테이블처럼 announcement_id, section_id 는 FK 없이 값으로만 참조한다. 문서와 실제 스키마가 어긋나면
--  어느 쪽이 맞는지 알 수 없어지므로, 엔티티와 이 파일은 항상 같은 제약만 가져야 한다.)
--
-- ddl-auto: validate 인 환경(prod 프로필)은 테이블이 없으면 api 가 기동 시 스키마 검증에서 실패하므로,
-- api 배포 전에 이 DDL 을 대상 DB 에 먼저 적용한다. 새 테이블이라 기존 데이터에는 영향이 없다.
-- ddl-auto: update 인 환경(dev 프로필)은 Hibernate 가 같은 테이블을 알아서 만든다.
CREATE TABLE IF NOT EXISTS announcement_popup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) NOT NULL,
    deleted_at TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL,
    announcement_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    -- 제목은 선택이라 NULL 을 허용한다. 빈 문자열은 저장하지 않고 NULL 로 정규화한다(AnnouncementPopup.create/updateTitle).
    title VARCHAR(200),
    content TEXT NOT NULL,
    image_file_id BIGINT,
    enabled BOOLEAN NOT NULL,
    -- JPA @Version. 교수가 팝업을 수정할 때만 오른다(알림 발송처럼 내용과 무관하게 저장하는 경로가 없다).
    -- 학생이 '일주일간 보지 않기'를 누른 시점의 값과 비교해 팝업이 바뀌었으면 다시 보여준다.
    version BIGINT NOT NULL,
    PRIMARY KEY (id),
    -- 공지사항 하나에 팝업은 하나. AnnouncementPopupRepositoryImpl.save 는 동시 등록이 이 제약에 걸리면
    -- AnnouncementPopupAlreadyExistsException 으로 바꾼다(서비스의 존재 확인만으로는 동시 요청을 못 막는다).
    -- deleted_at 을 무시하는 일반 유니크 제약이지만, 팝업은 삭제하지 않고 enabled 를 꺼서 숨기므로 문제가 없다.
    CONSTRAINT uk_announcement_popup_announcement UNIQUE (announcement_id)
);

-- 분반의 팝업 목록 조회용
CREATE INDEX IF NOT EXISTS idx_announcement_popup_section ON announcement_popup (section_id);
