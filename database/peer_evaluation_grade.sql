-- 상호평가·성적 엔티티 기반 DDL
-- section_id, milestone_id, user_id, team_id는 외부 Section/Milestone/User/Team 테이블이 develop에 합쳐진 뒤 FK를 후속 적용한다.

CREATE TABLE IF NOT EXISTS peer_evaluation_form (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL,
    milestone_id BIGINT NOT NULL,
    is_anonymous BOOLEAN NOT NULL,
    opens_at TIMESTAMP NOT NULL,
    closes_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT chk_peer_evaluation_form_period CHECK (opens_at < closes_at)
);

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_form_section_milestone
    ON peer_evaluation_form (section_id, milestone_id);

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_form_period
    ON peer_evaluation_form (opens_at, closes_at);

CREATE TABLE IF NOT EXISTS peer_evaluation_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id BIGINT NOT NULL,
    text VARCHAR(500) NOT NULL,
    type VARCHAR(16) NOT NULL,
    max_score NUMERIC(10, 2) NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT fk_peer_evaluation_question_form
        FOREIGN KEY (form_id) REFERENCES peer_evaluation_form (id),
    CONSTRAINT chk_peer_evaluation_question_type
        CHECK (type IN ('SCALE', 'TEXT')),
    CONSTRAINT chk_peer_evaluation_question_score_rule
        CHECK (
            (type = 'SCALE' AND max_score IS NOT NULL AND max_score > 0)
            OR (type = 'TEXT' AND max_score IS NULL)
        ),
    CONSTRAINT chk_peer_evaluation_question_display_order
        CHECK (display_order >= 0),
    CONSTRAINT chk_peer_evaluation_question_text
        CHECK (length(trim(text)) BETWEEN 1 AND 500)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_peer_evaluation_question_active_form_order
    ON peer_evaluation_question (form_id, display_order)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_question_form
    ON peer_evaluation_question (form_id);

CREATE TABLE IF NOT EXISTS peer_evaluation_response (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id BIGINT NOT NULL,
    evaluator_id VARCHAR(16) NOT NULL,
    target_id VARCHAR(16) NOT NULL,
    submitted_at TIMESTAMP NULL,
    self_contribution NUMERIC(10, 2) NULL,
    project_review_comment VARCHAR(2000) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT fk_peer_evaluation_response_form
        FOREIGN KEY (form_id) REFERENCES peer_evaluation_form (id),
    CONSTRAINT chk_peer_evaluation_response_student_number
        CHECK (length(trim(evaluator_id)) BETWEEN 1 AND 16 AND length(trim(target_id)) BETWEEN 1 AND 16),
    CONSTRAINT chk_peer_evaluation_response_self_contribution
        CHECK (self_contribution IS NULL OR (self_contribution >= 0 AND self_contribution <= 100)),
    CONSTRAINT chk_peer_evaluation_response_project_review_comment
        CHECK (project_review_comment IS NULL OR length(trim(project_review_comment)) <= 2000)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_peer_evaluation_response_active_pair
    ON peer_evaluation_response (form_id, evaluator_id, target_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_response_form
    ON peer_evaluation_response (form_id);

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_response_target
    ON peer_evaluation_response (target_id);

CREATE TABLE IF NOT EXISTS peer_evaluation_answer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    response_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    score NUMERIC(10, 2) NULL,
    text_answer VARCHAR(2000) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT fk_peer_evaluation_answer_response
        FOREIGN KEY (response_id) REFERENCES peer_evaluation_response (id),
    CONSTRAINT fk_peer_evaluation_answer_question
        FOREIGN KEY (question_id) REFERENCES peer_evaluation_question (id),
    CONSTRAINT chk_peer_evaluation_answer_one_value
        CHECK (
            (score IS NOT NULL AND text_answer IS NULL AND score >= 0)
            OR (score IS NULL AND text_answer IS NOT NULL AND length(trim(text_answer)) BETWEEN 1 AND 2000)
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_peer_evaluation_answer_active_response_question
    ON peer_evaluation_answer (response_id, question_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_answer_response
    ON peer_evaluation_answer (response_id);

CREATE INDEX IF NOT EXISTS idx_peer_evaluation_answer_question
    ON peer_evaluation_answer (question_id);

CREATE TABLE IF NOT EXISTS grade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    user_id VARCHAR(16) NOT NULL,
    team_score NUMERIC(10, 2) NOT NULL,
    peer_factor NUMERIC(10, 4) NOT NULL,
    final_score NUMERIC(10, 2) NOT NULL,
    manual_adjustment NUMERIC(10, 2) NOT NULL,
    snapshot JSONB NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT chk_grade_user
        CHECK (length(trim(user_id)) BETWEEN 1 AND 16),
    CONSTRAINT chk_grade_non_negative_scores
        CHECK (team_score >= 0 AND peer_factor >= 0 AND final_score >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_grade_active_user
    ON grade (section_id, team_id, user_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_grade_section_team
    ON grade (section_id, team_id);

CREATE INDEX IF NOT EXISTS idx_grade_user
    ON grade (user_id);
