CREATE TABLE IF NOT EXISTS professor_presentation_evaluation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    professor_id VARCHAR(20),
    memo TEXT,
    submitted_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,
    CONSTRAINT fk_professor_presentation_evaluation_milestone
        FOREIGN KEY (milestone_id) REFERENCES milestone (id),
    CONSTRAINT fk_professor_presentation_evaluation_team
        FOREIGN KEY (team_id) REFERENCES team (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_professor_presentation_evaluation_active_team
    ON professor_presentation_evaluation (milestone_id, team_id)
    WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS professor_presentation_evaluation_score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL,
    criterion_id BIGINT NOT NULL,
    score INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,
    CONSTRAINT fk_professor_presentation_evaluation_score_evaluation
        FOREIGN KEY (evaluation_id) REFERENCES professor_presentation_evaluation (id),
    CONSTRAINT fk_professor_presentation_evaluation_score_criterion
        FOREIGN KEY (criterion_id) REFERENCES team_evaluation_criterion (id),
    CONSTRAINT ck_professor_presentation_evaluation_score_non_negative CHECK (score >= 0),
    CONSTRAINT uk_professor_presentation_evaluation_score_evaluation_criterion
        UNIQUE (evaluation_id, criterion_id)
);

CREATE INDEX IF NOT EXISTS idx_professor_presentation_evaluation_score_criterion
    ON professor_presentation_evaluation_score (criterion_id);

-- Keep environments that applied the initial table definition compatible with BaseTimeEntity.
ALTER TABLE professor_presentation_evaluation_score
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP;
