CREATE TABLE IF NOT EXISTS project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL,
    topic_candidate_id BIGINT,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    goal TEXT NOT NULL,
    data_configuration JSONB,
    screen_configuration JSONB,
    key_features JSONB,
    demo_flow JSONB,
    project_schedule TEXT,
    repository_url VARCHAR(255),
    external_links JSONB,
    approval_status VARCHAR(50) NOT NULL,
    proposal_completed_at TIMESTAMP,
    -- 제안서 내용이 바뀔 때마다 증가한다. 이전 리비전의 동의는 무효가 된다.
    proposal_revision BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT fk_team_project FOREIGN KEY (team_id) REFERENCES team(id)
);

-- KD3-211 이전에는 data_configuration 이 TEXT 였다. Hibernate ddl-auto=update 는 PostgreSQL의
-- USING 절을 만들지 못하므로, 기존 DB에서는 이 스크립트를 먼저 실행해야 한다. JSON 텍스트는
-- 그대로 JSONB로, 평문은 JSON 문자열로 보존해 데이터 손실 없이 애플리케이션을 기동할 수 있다.
CREATE OR REPLACE FUNCTION pg_temp.to_jsonb_or_text(value TEXT)
RETURNS JSONB
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
    RETURN value::JSONB;
EXCEPTION WHEN OTHERS THEN
    RETURN to_jsonb(value);
END;
$$;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'project'
          AND column_name = 'data_configuration'
          AND data_type <> 'jsonb'
    ) THEN
        ALTER TABLE project
            ALTER COLUMN data_configuration TYPE JSONB
            USING pg_temp.to_jsonb_or_text(data_configuration);
    END IF;
END;
$$;

-- 부분 유니크 인덱스: 팀당 활성 프로젝트 1개 보장 (deleted_at IS NULL인 경우만)
CREATE UNIQUE INDEX IF NOT EXISTS uk_project_team_active 
ON project (team_id) 
WHERE deleted_at IS NULL;

-- 일반 인덱스
CREATE INDEX IF NOT EXISTS idx_project_team ON project (team_id);
CREATE INDEX IF NOT EXISTS idx_project_approval_status ON project (approval_status);
