CREATE TABLE IF NOT EXISTS team_evaluation_criterion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL,
    max_score INTEGER NOT NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT ck_team_evaluation_criterion_max_score_positive CHECK (max_score > 0),
    CONSTRAINT ck_team_evaluation_criterion_display_order_non_negative CHECK (display_order >= 0)
);

CREATE INDEX IF NOT EXISTS idx_team_evaluation_criterion_section_order
    ON team_evaluation_criterion (section_id, display_order);

COMMENT ON COLUMN team_evaluation_criterion.section_id IS 'Section 외부 FK는 Section 테이블 도입 후 적용한다.';

CREATE TABLE IF NOT EXISTS team_evaluation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    milestone_id BIGINT NOT NULL,
    rater_id VARCHAR(16) NOT NULL,
    ratee_team_id BIGINT NOT NULL,
    submitted_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_team_evaluation_active_milestone_rater_ratee
    ON team_evaluation (milestone_id, rater_id, ratee_team_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_team_evaluation_milestone_rater
    ON team_evaluation (milestone_id, rater_id);

CREATE INDEX IF NOT EXISTS idx_team_evaluation_ratee_team
    ON team_evaluation (ratee_team_id);

COMMENT ON COLUMN team_evaluation.milestone_id IS 'Milestone 외부 FK는 Milestone 테이블 도입 후 적용한다.';
COMMENT ON COLUMN team_evaluation.rater_id IS 'User 외부 FK는 User 테이블 도입 후 적용한다.';
COMMENT ON COLUMN team_evaluation.ratee_team_id IS 'Team 외부 FK는 Team 테이블 도입 후 적용한다.';

CREATE TABLE IF NOT EXISTS team_evaluation_score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_evaluation_id BIGINT NOT NULL,
    criterion_id BIGINT NOT NULL,
    score INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    CONSTRAINT fk_team_evaluation_score_evaluation
        FOREIGN KEY (team_evaluation_id) REFERENCES team_evaluation (id),
    CONSTRAINT fk_team_evaluation_score_criterion
        FOREIGN KEY (criterion_id) REFERENCES team_evaluation_criterion (id),
    CONSTRAINT ck_team_evaluation_score_non_negative CHECK (score >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_team_evaluation_score_active_evaluation_criterion
    ON team_evaluation_score (team_evaluation_id, criterion_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_team_evaluation_score_evaluation
    ON team_evaluation_score (team_evaluation_id);

CREATE INDEX IF NOT EXISTS idx_team_evaluation_score_criterion
    ON team_evaluation_score (criterion_id);
